#!/usr/bin/env node
/**
 * Build the name-origin animation as ONE standalone HTML file (2026-08-30).
 *
 *   node scripts/build-origin-html.mjs
 *   -> work/fluolingo-origin/fluolingo-origin.html
 *
 * Open it in any browser, mail it, put it on a stick. No server, no build, no
 * network — one file.
 *
 * WHY A SCRIPT RATHER THAN A HAND-WRITTEN PAGE. There must be exactly one
 * implementation of this animation. Dan rejected the first cut over a detail
 * of its interior spacing; a hand-written copy for sharing would answer that
 * note in one place and not the other, and the copy is the one people watch.
 * So this compiles the SAME two modules the app imports — `fluolingoOrigin.ts`
 * (stages, beats, layout arithmetic) and `fluolingoOriginRender.ts` (the DOM
 * renderer) — with the TypeScript already in devDependencies, and lifts the
 * palette straight out of `globals.css`. Nothing here restates the animation.
 *
 * The two compiled modules are concatenated into one inline <script>: the
 * renderer's single import of the other is dropped and the `export` keywords
 * come off, which is sound because they share no names. Both facts are
 * asserted below rather than assumed.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const ROOT = process.cwd();
const OUT_DIR = path.join(ROOT, "work", "fluolingo-origin");
const OUT = path.join(OUT_DIR, "fluolingo-origin.html");
const CSS = path.join(ROOT, "src", "app", "globals.css");

const die = (m) => {
  console.error(`build-origin-html: ${m}`);
  process.exit(1);
};

/* ── 1 · compile the two modules ─────────────────────────────────────────── */
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "origin-"));
execFileSync(
  "npx",
  ["tsc", "src/lib/fluolingoOrigin.ts", "src/lib/fluolingoOriginRender.ts",
   "--target", "es2022", "--module", "esnext", "--moduleResolution", "bundler",
   "--removeComments", "false", "--outDir", tmp],
  { cwd: ROOT, stdio: "inherit" },
);

const read = (f) => fs.readFileSync(path.join(tmp, f), "utf8");
let core = read("fluolingoOrigin.js");
let render = read("fluolingoOriginRender.js");

const imports = [...render.matchAll(/^import[\s\S]*?;$/gm)];
if (imports.length !== 1) die(`the renderer has ${imports.length} imports, expected exactly 1`);
render = render.replace(imports[0][0], "");

const strip = (s) => s.replace(/^export (?!type)/gm, "").replace(/^export type[\s\S]*?;$/gm, "");
core = strip(core);
render = strip(render);

// they are about to share one scope, so they had better not share a name
const names = (s) => [...s.matchAll(/^(?:const|let|function|class)\s+([A-Za-z_$][\w$]*)/gm)].map((m) => m[1]);
const clash = names(core).filter((n) => names(render).includes(n));
if (clash.length) die(`the two modules both declare ${clash.join(", ")}`);

/* ── 2 · lift the palette out of globals.css ─────────────────────────────── */
// --fluo-ink is declared TWICE in that file (the 10 Aug override block wins),
// so take the LAST declaration of every token, exactly as the cascade does.
const css = fs.readFileSync(CSS, "utf8");
const declared = (name) => {
  const hits = [...css.matchAll(new RegExp(`${name}\\s*:\\s*([^;]+);`, "g"))];
  if (!hits.length) die(`${name} is not declared in globals.css`);
  return hits[hits.length - 1][1].trim();
};
// ...and a token may point at another token: --fluo-ink is var(--cahier-ink),
// which is itself declared twice. Follow the chain, or the standalone page
// ships a var() with nothing behind it — the letters lose their ink and the
// frame loses its border, silently, because that is what CSS does with an
// unresolved custom property.
const tokenValue = (name, seen = new Set()) => {
  if (seen.has(name)) die(`${name} refers to itself`);
  seen.add(name);
  return declared(name).replace(/var\(\s*(--[\w-]+)\s*\)/g, (_, ref) => tokenValue(ref, seen));
};
const TOKENS = [
  "--fluo-ink", "--fluo-serif", "--fluo-bg",
  "--fluo-origin-ground", "--fluo-origin-flu", "--fluo-origin-o",
  "--fluo-origin-lin", "--fluo-origin-go",
  "--fluo-origin-field-1", "--fluo-origin-field-2",
];
const vars = TOKENS.map((t) => `      ${t}: ${tokenValue(t)};`).join("\n");

/* ── 3 · the page ────────────────────────────────────────────────────────── */
const html = `<!doctype html>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Fluolingo — where the name comes from</title>
<!-- GENERATED by scripts/build-origin-html.mjs. Do not edit: the animation
     lives in src/lib/fluolingoOrigin.ts + src/lib/fluolingoOriginRender.ts,
     and the palette in src/app/globals.css. Re-run the script instead. -->
<style>
  :root {
${vars}
  }
  html, body { margin: 0; height: 100%; }
  body {
    display: grid; place-items: center; padding: 16px;
    background: var(--fluo-bg);
    font-family: var(--fluo-serif);
  }
  #stage {
    position: relative; width: min(920px, 100%); overflow: hidden;
    font-family: var(--fluo-serif); font-weight: 900;
    background: var(--fluo-origin-ground); color: var(--fluo-ink);
    border: 2px solid var(--fluo-ink); border-radius: 16px;
    box-shadow: 0 6px 0 0 var(--fluo-ink);
    contain: layout paint; cursor: pointer; user-select: none;
  }
</style>
<div id="stage" role="img"
     aria-label="Fluency achieved on customisable linguistic goals — Fluolingo"></div>
<script type="module">
${core}
${render}
const stage = document.getElementById("stage");
const show = mountOrigin(stage);
stage.addEventListener("click", () => show.replay());
</script>
`;

if (/var\(--/.test(vars)) die(`a palette token is still unresolved:\n${vars}`);

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(OUT, html);
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`${path.relative(ROOT, OUT)} — ${(html.length / 1024).toFixed(1)} kB, one file, no dependencies`);
